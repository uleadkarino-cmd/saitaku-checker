import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const origin = 'https://saitaku-checker.saitaku-karino.workers.dev';
const { owner } = JSON.parse(await readFile('outputs/cloudflare-private/members.json', 'utf8'));
const authorization = 'Basic ' + Buffer.from(`owner:${owner.password}`).toString('base64');
for (const path of ['/admin', '/admin/quality', '/api/admin/inquiries', '/api/admin/inquiries/export']) {
  const response = await fetch(origin + path);
  assert.equal(response.status, 401, `Unauthenticated ${path}: ${response.status}`);
  assert.ok(response.headers.get('www-authenticate')?.startsWith('Basic '));
  console.log(`Protected ${path}: 401`);
}
const publicPage = await fetch(origin);
assert.equal(publicPage.status, 200);
assert.equal(publicPage.headers.get('www-authenticate'), null);
const visitorCookie = publicPage.headers.get('set-cookie')?.split(';')[0];
assert.ok(visitorCookie);
console.log('Public home without login: 200');
assert.equal((await fetch(origin + '/favicon.svg')).status, 200);
const visitorQuota = await fetch(origin + '/api/quota', { headers: { cookie: visitorCookie } });
assert.equal(visitorQuota.status, 200);
const visitorData = await visitorQuota.json();
assert.equal(visitorData.authenticated, true);
assert.equal(visitorData.email, null);
console.log('Public visitor quota and database: 200');
const headers = { authorization };
const page = await fetch(origin, { headers });
assert.equal(page.status, 200, 'Authenticated home page');
const html = await page.text();
assert.ok(html.includes('サイタク'));
console.log('Authenticated home: 200');
const asset = html.match(/(?:href|src)="([^" ]+\.css)"/)?.[1];
assert.ok(asset, 'CSS asset exists');
assert.equal((await fetch(new URL(asset, origin), { headers })).status, 200);
console.log('Authenticated CSS: 200');
const quota = await fetch(origin + '/api/quota', { headers });
assert.equal(quota.status, 200);
const data = await quota.json();
assert.equal(data.authenticated, true);
assert.equal(data.email, owner.email);
console.log('Authenticated quota and database: 200');
const admin = await fetch(origin + '/admin', { headers });
assert.equal(admin.status, 200, 'Admin page');
console.log('Authenticated admin: 200');
const spoof = await fetch(origin + '/api/admin/inquiries', { headers: { 'oai-authenticated-user-id': 'spoof', 'oai-authenticated-user-email': owner.email } });
assert.equal(spoof.status, 401);
console.log('Spoofed identity denied: 401');
